<?php

namespace App\Console\Commands;

use App\Enums\Permission;
use App\Enums\SystemRole;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Routing\Route as RoutingRoute;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Route;

#[Signature('hms:generate-docs {--check : Fail if the committed files are out of date instead of writing them}')]
#[Description('Regenerate docs/PERMISSIONS.md and docs/ROUTES.md from the code')]
class GenerateReferenceDocs extends Command
{
    public function handle(): int
    {
        $files = [
            base_path('docs/PERMISSIONS.md') => $this->permissions(),
            base_path('docs/ROUTES.md') => $this->routes(),
        ];

        $stale = [];

        foreach ($files as $path => $content) {
            if ($this->option('check')) {
                if (! is_file($path) || File::get($path) !== $content) {
                    $stale[] = basename($path);
                }

                continue;
            }

            File::ensureDirectoryExists(dirname($path));
            File::put($path, $content);
            $this->components->info('Wrote '.basename($path));
        }

        if ($stale !== []) {
            $this->components->error('Out of date: '.implode(', ', $stale).'. Run php artisan hms:generate-docs.');

            return self::FAILURE;
        }

        return self::SUCCESS;
    }

    private function permissions(): string
    {
        $roles = SystemRole::cases();
        $lines = [
            '# Permissions matrix',
            '',
            '> Generated by `php artisan hms:generate-docs` from `App\\Enums\\SystemRole`. Do not edit by hand.',
            '',
            'These are the permissions each built-in role receives when roles are seeded. Administrators can',
            'adjust custom roles in **Administration → Roles & Permissions**; nobody can grant a permission they',
            'do not hold themselves, and the protected Super Admin account cannot be edited or removed by others.',
            '',
        ];

        $groups = [];

        foreach (Permission::cases() as $permission) {
            $groups[$permission->group()][] = $permission;
        }

        $header = '| Permission | '.implode(' | ', array_map(fn (SystemRole $role): string => $role->value, $roles)).' |';
        $divider = '|---|'.str_repeat(':---:|', count($roles));

        foreach ($groups as $group => $permissions) {
            $lines[] = "## {$group}";
            $lines[] = '';
            $lines[] = $header;
            $lines[] = $divider;

            foreach ($permissions as $permission) {
                $cells = array_map(fn (SystemRole $role): string => in_array($permission, $role->defaultPermissions(), true) ? '✓' : '', $roles);
                $lines[] = "| `{$permission->value}` | ".implode(' | ', $cells).' |';
            }

            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    private function routes(): string
    {
        $lines = [
            '# Route reference',
            '',
            '> Generated by `php artisan hms:generate-docs`. Do not edit by hand.',
            '',
            'Back-office routes (`/admin`) also require a signed-in, verified, active staff account; the permission',
            'each action needs is enforced in its controller or form request. See [PERMISSIONS.md](PERMISSIONS.md).',
            '',
        ];

        $sections = ['Public website' => [], 'Guest account' => [], 'Back office' => [], 'Integrations' => [], 'Authentication & settings' => []];

        /** @var RoutingRoute $route */
        foreach (Route::getRoutes()->getRoutes() as $route) {
            $name = (string) $route->getName();
            $uri = '/'.ltrim($route->uri(), '/');

            if ($name === '' || str_starts_with($name, 'storage.') || str_starts_with($name, 'boost.') || str_contains($uri, '_boost') || str_starts_with($uri, '/_')) {
                continue;
            }

            $section = match (true) {
                str_starts_with($name, 'admin.') => 'Back office',
                str_starts_with($name, 'account.') => 'Guest account',
                str_starts_with($name, 'webhooks.') => 'Integrations',
                str_starts_with($name, 'site.') || in_array($name, ['home', 'sitemap', 'currency.update'], true) => 'Public website',
                default => 'Authentication & settings',
            };

            $methods = implode(', ', array_diff($route->methods(), ['HEAD']));
            $sections[$section][$uri.' '.$methods] = "| {$methods} | `{$uri}` | `{$name}` |";
        }

        foreach ($sections as $title => $rows) {
            if ($rows === []) {
                continue;
            }

            ksort($rows);
            $lines[] = "## {$title}";
            $lines[] = '';
            $lines[] = '| Method | URI | Name |';
            $lines[] = '|---|---|---|';
            array_push($lines, ...array_values($rows));
            $lines[] = '';
        }

        return implode("\n", $lines);
    }
}
